create table if not exists public.quiz_scores (
  id bigint generated by default as identity primary key,
  username text not null check (char_length(username) between 1 and 24),
  mode text not null,
  correct integer not null check (correct >= 0),
  total integer not null check (total > 0),
  percent integer not null check (percent between 0 and 100),
  seconds integer not null check (seconds >= 0),
  created_at timestamptz not null default now()
);
alter table public.quiz_scores enable row level security;
drop policy if exists "Public can read leaderboard" on public.quiz_scores;
create policy "Public can read leaderboard" on public.quiz_scores for select to anon using (true);
drop policy if exists "Public can submit scores" on public.quiz_scores;
create policy "Public can submit scores" on public.quiz_scores for insert to anon with check (
  char_length(username) between 1 and 24 and percent between 0 and 100 and total > 0
);
grant select, insert on public.quiz_scores to anon;
grant usage, select on sequence public.quiz_scores_id_seq to anon;
